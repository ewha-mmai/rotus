def load_entries(path: str) -> List[Dict[str, Any]]:
    ext = os.path.splitext(path)[1].lower()

    if ext == ".jsonl":
        rows: List[Dict[str, Any]] = []
        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                obj = json.loads(line)
                if isinstance(obj, dict):
                    rows.append(obj)
                else:
                    raise ValueError("Each line in JSONL input must be a JSON object.")
        return rows

    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    if isinstance(data, list):
        return data
    raise ValueError("Input must be a JSON list (.json) or JSON objects per line (.jsonl).")


def save_jsonl(path: str, rows: List[Dict[str, Any]]) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

def save_json(path: str, obj: Any) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)

def get_final_answer_text(entry: Dict[str, Any]) -> Optional[str]:
    for k in ["model_answer"]:
        v = entry.get(k)
        if isinstance(v, str) and v.strip():
            return v.strip()
    return None

def get_question_text(entry: Dict[str, Any]) -> str:
    q = entry.get("question")
    if isinstance(q, str) and q.strip():
        return q.strip()
    return ""

def get_ground_truth_text(entry: Dict[str, Any]) -> str:
    gt = entry.get("ground_truth")
    if isinstance(gt, str) and gt.strip():
        return gt.strip()
    return ""

def get_is_unanswerable(entry: Dict[str, Any]) -> bool:
    if "is_unanswerable" in entry:
        return bool(entry.get("is_unanswerable"))
    return False

def parse_input_tags(input_path: str) -> Tuple[str, str]:
    base = os.path.splitext(os.path.basename(input_path))[0]
    parts = base.split("_", 1)
    if len(parts) == 2:
        return base, parts[1]
    return base, "unknown_model"


def resolve_api_key(args: argparse.Namespace) -> str:
    key = args.api_key or os.environ.get("OPENAI_API_KEY")
    if not key:
        raise ValueError("OpenAI API key required: --api_key or OPENAI_API_KEY env var")
    return key

def resolve_output_dir(input_path: str) -> str:
    return os.path.dirname(os.path.abspath(input_path)) or "."

