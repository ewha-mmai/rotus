def tf_from_text(s: str):
    if not isinstance(s, str):
        return None
    t = s.strip().upper()
    if t == "TRUE":
        return True
    if t == "FALSE":
        return False
    return None

def make_batch_requests(
    entries: List[Dict[str, Any]],
    model: str,
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:

    batch_lines = []
    meta = []

    for i, e in enumerate(entries):
        idx = e.get("index", i)
        question = get_question_text(e)
        gt = get_ground_truth_text(e)
        is_unans = get_is_unanswerable(e)
        ans = get_final_answer_text(e)
        meta.append({
            "row_i": i,
            "index": idx,
            "is_unanswerable": is_unans,
            "question": question,
            "ground_truth": gt,
            "eval_answer": ans,
        })

        if not ans:
            continue

        # Always check refusal regardless of answerability
        refusal_prompt = REFUSAL_CHECK_PROMPT.format(question=question, response=ans)
        batch_lines.append({
            "custom_id": f"{i}::refusal",
            "method": "POST",
            "url": "/v1/chat/completions",
            "body": {
                "model": model,
                "messages": [{"role": "user", "content": refusal_prompt}],
            }
        })

        # Correctness check only for answerable questions
        if not is_unans:
            acc_prompt = ACCURACY_CHECK_PROMPT.format(query=question, gt_answer=gt, pred_answer=ans)
            batch_lines.append({
                "custom_id": f"{i}::correct",
                "method": "POST",
                "url": "/v1/chat/completions",
                "body": {
                    "model": model,
                    "messages": [{"role": "user", "content": acc_prompt}],
                }
            })

    return batch_lines, meta


def write_jsonl(path: str, objs: List[Dict[str, Any]]) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for o in objs:
            f.write(json.dumps(o, ensure_ascii=False) + "\n")


def read_jsonl(path: str) -> List[Dict[str, Any]]:
    out = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out

