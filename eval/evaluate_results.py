def safe_div(a: float, b: float) -> float:
    return a / b if b else 0.0

def compute_metrics(rows: List[Dict[str, Any]]) -> Dict[str, Any]:
    # Exclude rows with no model_answer from acc and f1 computation
    rows = [r for r in rows if r.get("eval_answer") or r.get("model_answer", "")]
    n = len(rows)
    if n == 0:
        return {
            "n": 0,
            "n_answerable": 0,
            "n_unanswerable": 0,
            "acc": 0.0,
            "overall_acc": 0.0,
            "precision": 0.0,
            "recall": 0.0,
            "f1": 0.0,
            "tp": 0, "fp": 0, "fn": 0, "tn": 0,
        }

    # ACC: based on judge_correct for answerable questions
    ans_rows = [r for r in rows if not bool(r.get("is_unanswerable", False))]
    acc = safe_div(sum(r.get("judge_correct", False) for r in ans_rows), len(ans_rows)) if ans_rows else 0.0

    # F1: positive = unanswerable (should refuse), predicted positive = refused
    # TP: unanswerable + refused
    # FN: unanswerable + not refused
    # FP: answerable + refused
    # TN: answerable + not refused
    tp = fp = fn = tn = 0
    for r in rows:
        gt_unanswerable = bool(r.get("is_unanswerable", False))
        pred_refused = bool(r.get("judge_refusal", False))
        if gt_unanswerable and pred_refused:
            tp += 1
        elif gt_unanswerable and not pred_refused:
            fn += 1
        elif not gt_unanswerable and pred_refused:
            fp += 1
        else:
            tn += 1

    precision = safe_div(tp, tp + fp)
    recall = safe_div(tp, tp + fn)
    f1 = safe_div(2 * precision * recall, precision + recall) if (precision + recall) else 0.0
    overall_acc = safe_div(tp + tn, n)

    return {
        "n": n,
        "n_answerable": len(ans_rows),
        "n_unanswerable": n - len(ans_rows),
        "acc": acc,
        "overall_acc": overall_acc,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "tp": tp, "fp": fp, "fn": fn, "tn": tn,
    }


def make_summary_table(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    out = []
    out.append({"group": "ALL", **compute_metrics(rows)})
    return out


def save_tables(summary_rows: List[Dict[str, Any]], csv_path: str, md_path: str) -> None:
    os.makedirs(os.path.dirname(csv_path) or ".", exist_ok=True)
    if pd is not None:
        df = pd.DataFrame(summary_rows)
        df.to_csv(csv_path, index=False)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(df.to_markdown(index=False))
    else:
        headers = list(summary_rows[0].keys()) if summary_rows else ["group"]
        with open(csv_path, "w", encoding="utf-8") as f:
            f.write(",".join(headers) + "\n")
            for r in summary_rows:
                f.write(",".join(str(r.get(h, "")) for h in headers) + "\n")
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(json.dumps(summary_rows, ensure_ascii=False, indent=2))


