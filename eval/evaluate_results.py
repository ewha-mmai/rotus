def cmd_submit(args):
    client = OpenAI(api_key=resolve_api_key(args))
    entries = load_entries(args.input_path)
    base, _ = parse_input_tags(args.input_path)
    out_dir = args.out_dir or resolve_output_dir(args.input_path)

    judge_model = args.judge_model

    batch_lines, meta = make_batch_requests(
        entries,
        model=judge_model,
    )

    batch_jsonl_path = os.path.join(out_dir, f"{base}_judge_batch_input.jsonl")
    meta_path = os.path.join(out_dir, f"{base}_judge_meta.json")

    os.makedirs(out_dir, exist_ok=True)
    write_jsonl(batch_jsonl_path, batch_lines)
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)

    input_file = client.files.create(
        file=open(batch_jsonl_path, "rb"),
        purpose="batch"
    )

    batch = client.batches.create(
        input_file_id=input_file.id,
        endpoint="/v1/chat/completions",
        completion_window="24h",
        metadata={"source": base, "judge_model": judge_model}
    )

    print("Submitted batch:")
    print("  batch_id:", batch.id)
    print("  input_file_id:", input_file.id)
    print("  batch_input_jsonl:", batch_jsonl_path)
    print("  meta_json:", meta_path)
    print("\nNext:")
    print(f"  python {os.path.basename(__file__)} collect --input_path {args.input_path} --batch_id {batch.id}")


def cmd_collect(args):
    client = OpenAI(api_key=resolve_api_key(args))

    base, file_model = parse_input_tags(args.input_path)
    out_dir = args.out_dir or resolve_output_dir(args.input_path)
    meta_path = os.path.join(out_dir, f"{base}_judge_meta.json")
    if not os.path.exists(meta_path):
        raise FileNotFoundError(f"Missing meta file: {meta_path} (run submit first)")

    with open(meta_path, "r", encoding="utf-8") as f:
        meta = json.load(f)

    batch = client.batches.retrieve(args.batch_id)
    status = getattr(batch, "status", None)
    print("Batch status:", status)

    if status != "completed":
        print("Batch not completed yet. (status != completed)")
        return

    output_file_id = getattr(batch, "output_file_id", None)
    if not output_file_id:
        error_file_id = getattr(batch, "error_file_id", None)
        request_counts = getattr(batch, "request_counts", None)

        if error_file_id:
            err_path = os.path.join(out_dir, f"{base}_batch_errors.jsonl")
            err_content = client.files.content(error_file_id).read().decode("utf-8")
            with open(err_path, "w", encoding="utf-8") as f:
                f.write(err_content)
            raise RuntimeError(
                "Batch completed but output_file_id is missing. "
                f"Likely all requests failed. request_counts={request_counts}. "
                f"Saved error details to: {err_path}"
            )

        raise RuntimeError(
            "Batch completed but output_file_id is missing and error_file_id is also missing. "
            f"request_counts={request_counts}"
        )

    content = client.files.content(output_file_id).read().decode("utf-8")
    out_lines = [json.loads(l) for l in content.splitlines() if l.strip()]

    judged: Dict[str, Optional[bool]] = {}
    for o in out_lines:
        cid = o.get("custom_id")
        resp = o.get("response", {})
        try:
            body = resp.get("body", {})
            text = body["choices"][0]["message"]["content"]
        except Exception:
            text = ""
        judged[cid] = tf_from_text(text)

    entries = load_entries(args.input_path)
    results = []
    for m in meta:
        i = m["row_i"]
        e = entries[i]
        ans = m.get("eval_answer")

        is_unans = bool(m.get("is_unanswerable", get_is_unanswerable(e)))

        if not ans:
            out = dict(e)
            out.update({
                "eval_answer": None,
                "judge_refusal": False,
                "judge_correct": False,
                "eval_acc": 0.0,
                "eval_note": "no_answer",
            })
            results.append(out)
            continue

        # Refusal is now checked for ALL questions (answerable + unanswerable)
        judge_refusal = bool(judged.get(f"{i}::refusal") is True)

        # Correctness only for answerable questions
        judge_correct = False
        if not is_unans:
            judge_correct = bool(judged.get(f"{i}::correct") is True)

        if is_unans:
            eval_acc = 1.0 if judge_refusal else 0.0
        else:
            eval_acc = 1.0 if judge_correct else 0.0

        out = dict(e)
        out.update({
            "eval_answer": ans,
            "judge_refusal": judge_refusal,
            "judge_correct": judge_correct,
            "eval_acc": float(eval_acc),
            "eval_note": "",
            "judge_model": args.judge_model,
            "eval_model": file_model,
            "batch_id": args.batch_id,
            "is_unanswerable": is_unans,
        })
        results.append(out)

    eval_path = os.path.join(out_dir, f"{base}_eval_output.json")
    save_json(eval_path, results)
    print("Saved:", eval_path)

    summary = make_summary_table(results)
    csv_path = os.path.join(out_dir, f"{base}_summary.csv")
    md_path = os.path.join(out_dir, f"{base}_summary.md")
    save_tables(summary, csv_path, md_path)
    print("Saved:", csv_path)
    print("Saved:", md_path)

    total = len(results)
    no_answer = sum(1 for r in results if not (r.get("eval_answer") or r.get("model_answer", "")))
    no_answer_ratio = safe_div(no_answer, total)

    m = summary[0]
    print("\n" + "=" * 60)
    print(f"total={total}  no_answer={no_answer}  ({no_answer_ratio:.2%})")
    print(f"n (non-empty)={m['n']}  (answerable={m['n_answerable']}, unanswerable={m['n_unanswerable']})")
    print(f"ACC (answerable judge_correct)     : {m['acc']:.4f}")
    print(f"Overall ACC (TP+TN)/(TP+FP+FN+TN) : {m['overall_acc']:.4f}")
    print(f"F1                                 : {m['f1']:.4f}  (P={m['precision']:.4f}, R={m['recall']:.4f})")
    print(f"  TP={m['tp']}  FP={m['fp']}  FN={m['fn']}  TN={m['tn']}")
    print(f"  (TP=unanswerable+refused, FN=unanswerable+answered, FP=answerable+refused, TN=answerable+answered)")
    print("=" * 60)

def main():
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)

    ps = sub.add_parser("submit")
    ps.add_argument("--input_path", required=True)
    ps.add_argument("--out_dir", required=False)
    ps.add_argument("--api_key", required=False)
    ps.add_argument("--judge_model", default="gpt-5-mini")

    pc = sub.add_parser("collect")
    pc.add_argument("--input_path", required=True)
    pc.add_argument("--out_dir", required=False)
    pc.add_argument("--api_key", required=False)
    pc.add_argument("--batch_id", required=True)
    pc.add_argument("--judge_model", default="gpt-5-mini")

    args = p.parse_args()

    if args.cmd == "submit":
        cmd_submit(args)
    else:
        cmd_collect(args)

if __name__ == "__main__":
    main()
