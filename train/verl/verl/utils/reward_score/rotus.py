def compute_score(
    solution_str: str,
    ground_truth: str,
    extra_info: Optional[Dict] = None,
    tool_tag: Optional[str] = None,
    max_assistant_turns: Optional[int] = None,
    **kwargs
) -> Dict[str, float]:
    extra_info = extra_info or {}
    question_text = extra_info.get('question', '')
    is_unanswerable = extra_info.get('is_unanswerable', False)
    tool_tag = tool_tag or extra_info.get('tool_tag', 'tool_call')

    max_turns = int(max_assistant_turns) if max_assistant_turns is not None else 5
    optimal_tool_calls = max_turns // 2
    if "tool_call_penalty" in (extra_info or {}):
        penalty_rate = float(extra_info["tool_call_penalty"])
    else:
        penalty_rate = 1.0 / optimal_tool_calls if optimal_tool_calls > 0 else 1.0

    # 1. Validate format
    format_info = check_format(solution_str, tool_tag=tool_tag)
    format_reward = 1.0 if format_info["is_valid"] else 0.0
    tool_call_count = format_info["tool_call_count"]

    # 2. Extract answer
    predict_no_think = solution_str.split('</think>')[-1].strip() if '</think>' in solution_str else solution_str
    answer_text = extract_answer(predict_no_think)

    # 3. If no answer, accuracy = 0
    if not answer_text:
        tags = []
        for tag in ['think', tool_tag, 'answer']:
            cnt = solution_str.count(f'<{tag}>')
            if cnt > 0:
                tags.append(f'<{tag}>x{cnt}')
        print(f'[REWARD] NO_ANSWER | tags=[{",".join(tags)}] | output(last 150)=...{solution_str[-150:]}')
        return {
            "score": format_reward,  # format score only
            "acc": 0.0,
            "format": format_reward,
            "tool_call_count": tool_call_count,
            "tool_call_penalty": 0.0,
        }

    # 4. Penalize overly long answers (to prevent hacking)
    if len(answer_text) >= 500:
        return {
            "score": format_reward * 0.5,
            "acc": 0.0,
            "format": format_reward * 0.5,
            "tool_call_count": tool_call_count,
            "tool_call_penalty": 0.0,
        }

    # 5. Validate accuracy
    if is_unanswerable:
        # Unanswerable question (is_unanswerable=1): check if model refused using REFUSAL_CHECK_PROMPT
        is_refused = llm_judge_refusal(question_text, answer_text)
        acc_reward = 1.0 if is_refused else 0.0
    else:
        # Answerable question (is_unanswerable=0): check if answer is correct using ACCURACY_CHECK_PROMPT
        is_correct = llm_judge_accuracy(question_text, ground_truth, answer_text)
        acc_reward = 1.0 if is_correct else 0.0

    # 6. Compute tool call penalty (applied only to unanswerable questions)
    if is_unanswerable:
        deviation = abs(tool_call_count - optimal_tool_calls)
        tool_call_penalty = deviation * penalty_rate
        acc_with_penalty = acc_reward * max(0.0, 1.0 - tool_call_penalty)
    else:
        tool_call_penalty = 0.0
        acc_with_penalty = acc_reward

    # 7. Compute final score
    # unanswerable: total_reward = format_reward + accuracy_reward * max(0, 1 - |calls - optimal| * rate)
    # answerable:   total_reward = format_reward + accuracy_reward
    final_score = format_reward + acc_with_penalty

    # Tag summary
    tags = []
    for tag in ['think', tool_tag, 'answer']:
        cnt = solution_str.count(f'<{tag}>')
        if cnt > 0:
            tags.append(f'<{tag}>x{cnt}')
    ans_short = answer_text[:80] + '...' if len(answer_text) > 80 else answer_text
    # print(f'[REWARD] tags=[{",".join(tags)}] | ans={ans_short} | '
    #       f'acc={acc_reward} fmt={format_reward} tool={tool_call_count} penalty={tool_call_penalty:.1f} '
    #       f'final={final_score:.2f}')

    return {
        "score": final_score,
        "acc": acc_reward,
        "format": format_reward,
        "tool_call_count": tool_call_count,
        "tool_call_penalty": tool_call_penalty,
    }


def compute_score_acc(solution_str: str, ground_truth: str, extra_info: Optional[Dict] = None, **kwargs) -> Dict[str, float]:
    """Compute accuracy score only"""
    result = compute_score(solution_str, ground_truth, extra_info)
    return {
        "score": result["acc"],
        "acc": result["acc"],
    }
